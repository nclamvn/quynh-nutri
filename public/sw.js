// Minimal offline-read service worker (R-PWA-1). Network-first for navigations
// so the plan/list are fresh online; cache fallback keeps them readable offline.
const CACHE = "bua-com-v1";
const SHELL = ["/week", "/shopping", "/dishes", "/nutrition", "/settings", "/manifest.webmanifest", "/icon.svg"];

self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(SHELL)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (e) => {
  e.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (e) => {
  const { request } = e;
  if (request.method !== "GET") return;
  const isNav = request.mode === "navigate";

  e.respondWith(
    fetch(request)
      .then((res) => {
        const copy = res.clone();
        caches.open(CACHE).then((c) => c.put(request, copy)).catch(() => {});
        return res;
      })
      .catch(() => caches.match(request).then((hit) => hit ?? (isNav ? caches.match("/week") : undefined))),
  );
});
